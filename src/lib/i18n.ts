i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: "ar",
    supportedLngs: ['en', 'ar', 'fr', 'es', 'hi', 'ur', 'zh'],
    nonExplicitSupportedLngs: true,
    load: 'languageOnly',
    interpolation: {
      escapeValue: false
    }
  });

const applyDirection = (lng?: string) => {
  const rtl = isRtlLanguage(lng);
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.documentElement.lang = (lng || i18n.language || 'ar').split('-')[0];
};

try {
  const customStr = typeof window !== 'undefined' ? window.localStorage.getItem('jaknooma_custom_translations') : null;
  if (customStr) {
    const parsed = JSON.parse(customStr);
    Object.keys(parsed).forEach((lng) => {
      if (parsed[lng] && typeof parsed[lng] === 'object') {
        i18n.addResourceBundle(lng, 'translation', parsed[lng], true, true);
      }
    });
  }
} catch {
  // Ignore invalid storage data
}

i18n.on('languageChanged', (lng) => {
  applyDirection(lng);
});

applyDirection(i18n.language);

export default i18n;
