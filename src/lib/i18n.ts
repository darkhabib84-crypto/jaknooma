export function isRtlLanguage(lng?: string): boolean {
  const code = (lng || i18n.language || 'ar').toLowerCase();
  return code.startsWith('ar') || code.startsWith('ur');
}

export function formatPrice(value: number | string | undefined | null): string {
  if (value === undefined || value === null || value === '') return '0';
  const num = typeof value === 'number' ? value : parseFloat(String(value).replace(/,/g, ''));
  if (isNaN(num)) return String(value);
  const hasDecimals = num % 1 !== 0;
  return num.toLocaleString('en-US', {
    minimumFractionDigits: hasDecimals ? 2 : 0,
    maximumFractionDigits: 2,
  });
}

